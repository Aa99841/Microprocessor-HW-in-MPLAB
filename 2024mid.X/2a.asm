    #include<p18f4520.inc>
    CONFIG OSC = INTIO67
    CONFIG WDT = OFF
    org 0x00

    main:
    ; INPUT
	MOVLB 0x3  ;BSR = 3
	MOVLW 0X65
	MOVWF 0X00, 1
	MOVLW 0X06
	MOVWF 0X01, 1
	MOVLW 0X03
	MOVWF 0X02, 1
	MOVLW 0X65
	MOVWF 0X03, 1
	MOVLW 0X0C
	MOVWF 0X04, 1
	MOVLW 0X04
	MOVWF 0X05, 1
	MOVLW 0XF7
	MOVWF 0X06, 1
	MOVLW 0X32
	MOVWF 0X07, 1
	MOVLW 0X50
	MOVWF 0X08, 1
	MOVLW 0X00
	MOVWF 0X09, 1
	
	; HEAD
	MOVLW 0X03
	MOVWF 0X10,1
	
	;TAIL
	MOVLW 0X06
	MOVWF 0X11,1
	
	;LOOP COUNT
	MOVF 0X310,W
	SUBWF 0X311,W
	MOVWF 0X12,1
	
	MOVLW 0X01
	BTFSC 0X312,0
	ADDWF 0X312
	BCF     STATUS, C
	RRCF 0X312	
	
	LFSR 0, 0x300    ; FSR0 point to 0x300(H)
	LFSR 1, 0x300    ; FSR1 point to 0x300(T)
	
    FINDHEAD:
	MOVF POSTINC0,W
	DECF 0X310
	BNZ FINDHEAD
	
    FINDEND:
	MOVF POSTINC1,W
	DECF 0X311
	BNZ FINDEND
	
    SWITCH:
	MOVFF INDF0,WREG
	MOVFF INDF1,INDF0
	MOVFF WREG, INDF1
	
	MOVF POSTINC0,W
	MOVF POSTDEC1,W
	
	DECF 0X312
	BNZ SWITCH
	
    LAST:
	NOP
	
