List p=18f4520
    #include<p18f4520.inc>
    CONFIG OSC = INTIO67
    CONFIG WDT = OFF
    org 0x00
    
    main:
	;LIST 1
	MOVLW 0X08
	MOVWF 0X00
	MOVLW 0X09
	MOVWF 0X01
	MOVLW 0X02
	MOVWF 0X02
	
	;LIST 2
	MOVLW 0X02
	MOVWF 0X10
	MOVLW 0X03
	MOVWF 0X11
	MOVLW 0X04
	MOVWF 0X12
	
	LFSR 0, 0x00
	LFSR 2, 0X20
	
	MOVLW 0X04
	MOVWF 0X30
	
    COMPARELOOP1:
	LFSR 1, 0x10
	DECF 0X30
	BZ PART2
	MOVLW 0X04
	MOVWF 0X31
	
    COMPARE1:
	DECF 0X31
	BZ UNIQUE1
	MOVF POSTINC1,W
	CPFSEQ INDF0
	    GOTO COMPARE1
	MOVF POSTINC0,W
	GOTO COMPARELOOP1
	
    UNIQUE1:
	MOVFF INDF0, POSTINC2
	MOVF POSTINC0
	GOTO COMPARELOOP1
	
    PART2:
	LFSR 0, 0x10
	
	MOVLW 0X04
	MOVWF 0X30
	
    COMPARELOOP2:
	LFSR 1, 0x00
	DECF 0X30
	BZ LAST
	MOVLW 0X04
	MOVWF 0X31
	
    COMPARE2:
	DECF 0X31
	BZ UNIQUE2
	MOVF POSTINC1,W
	CPFSEQ INDF0
	    GOTO COMPARE2
	MOVF POSTINC0,W
	GOTO COMPARELOOP2
	
    UNIQUE2:
	MOVFF INDF0, POSTINC2
	MOVF POSTINC0
	GOTO COMPARELOOP2
	
    LAST:
	NOP
    
  end


