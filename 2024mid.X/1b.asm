List p=18f4520
    #include<p18f4520.inc>
    CONFIG OSC = INTIO67
    CONFIG WDT = OFF
    org 0x00
    
    ; 16 bits division 
    division macro xh, xl, yh, yl
	MOVFF xh, 0x00
	MOVFF xl, 0x01
	MOVFF yh, 0x02
	MOVFF yl, 0x03
	
    DIV:
	MOVF 0X00, W  ;WREG = A
	SUBWF 0X02,W  ;WREG = WREG - B
	BNC DIV_SUB    ;B < A
	MOVF 0X00, W
	CPFSEQ 0X02
	GOTO DIV_DONE
	GOTO COMPARE2
	
    COMPARE2:
	MOVF 0X03, W  ;WREG = D
	SUBWF 0X01,W  ;WREG = WREG - C
	BC DIV_SUB     ;C >= D
	GOTO DIV_DONE
	
    DIV_SUB:
	;? = [0x50][0x51]
	MOVLW 0X01
	ADDWF 0X51,W
	MOVWF 0X51
	
	MOVLW 0X00
	ADDWFC 0X50,W
	MOVWF 0X50
	
	MOVF    0X03, W
	SUBWF   0X01, F
	MOVF    0X02, W
	SUBWFB  0X00, F
	
	GOTO DIV
	
    DIV_DONE:
	;?? = [0x14][0x15]
	MOVFF 0X00,WREG
	MOVWF 0X14
	MOVFF 0X01,WREG
	MOVWF 0X15
    endm
    
    ;C(N,K) = N!/K!(N-K)!
    FACT macro N,K
 
	MOVLW N
	MOVWF 0X11
	MOVWF 0X21 ;N! L
	
	
	MOVLW K
	MOVWF 0X12
	MOVWF 0X31 ;K!
	
	MOVF 0X12,W
	SUBWF 0X11,W
	MOVWF 0X13
	MOVWF 0X41 ;(N-K)!
	
    ; n! / k! {n*(n-1)*(n-2)....(k+1)}
    NDIVKLOOP:
	DECF 0X11
	MOVF 0X12,W
	CPFSGT 0X11 ; 0X11>0X12 SKIP
	    GOTO NSUBKLOOP
	    
    COUNT:
	MOVF 0X21,W
	MULWF 0X11
	
	MOVFF PRODL ,0X21
	MOVFF PRODH, 0X22
	
	MOVF 0X20,W
	MULWF 0X11
	
	BCF STATUS, C
	MOVF 0X22,W
	ADDWF PRODL,W
	MOVWF 0X20
	
	GOTO NDIVKLOOP

    ; (n-k)!
    NSUBKLOOP:
	DECF 0X13
	BZ CLAST
	MOVF 0X41,W
	MULWF 0X13
	
	MOVFF PRODL ,0X41
	MOVFF PRODH, 0X42
	
	MOVF 0X40,W
	MULWF 0X13
	
	BCF STATUS, C
	MOVWF 0X42
	ADDWF PRODL,W
	MOVWF 0X40
	
	GOTO NSUBKLOOP

	
    CLAST:
	division 0x20,0x21,0x40,0x41
	MOVFF 0X51,0X00
    endm



    MAIN:
	FACT 0X05,0X03
	NOP

END