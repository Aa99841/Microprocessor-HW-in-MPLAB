List p=18f4520
    #include<p18f4520.inc>
    CONFIG OSC = INTIO67
    CONFIG WDT = OFF
    org 0x00

    MOVLW 0XFE ;Q
    MOVWF 0X00
    MOVLW 0X05
    MOVWF 0X01 ;M
    
    MOVLW 0X00
    MOVWF 0X10 ;A
    MOVLW 0X00
    MOVWF 0X11 ;Q(-1)
    MOVLW 0X00
    MOVLW 0X12 ;The rightest bit of A
    MOVLW 0X04
    MOVLW 0X13 ;COUNT
    
    CHECKNEGATIVE0:
	CPFSGT 0X00
	GOTO COMPLENT0 
    
    CHECKNEGATIVE1:
	CPFSLT 0X01
	GOTO COMPLENT1

    LOOP:
	DECF 0X13
	CPFSEQ 0X13
	GOTO BOOTH
	GOTO LAST
    
    BOOTH:
	BTFSS 0X00,0
	GOTO Q00
	GOTO Q01
	
    Q00:
	BTFSS 0X11,0
	GOTO SHIFT
	GOTO ADDM
    Q01:
	BTFSS 0X11, 0
	GOTO SUBM
	GOTO SHIFT
	
    ADDM:
	MOVFF 0X01,WREG
	ADDWF 0X10
	
    SUBM:
	MOVFF 0X01,WREG
	SUBWF 0X10
	
    SHIFT:
	;Q(-1)
	MOVFF 0X00,WREG
	ANDLW B'00000001'
	MOVWF 0X11
	
	;The rightest bit of A
	MOVFF 0X10,WREG
	ANDLW B'00000001'
	MOVWF 0X12
	
    SHIFTA:
	; A SHIFT RIGHT(NEGATIVE THEN 1)
	BTFSC 0X10, 7
	GOTO SETA1
	MOVFF 0X10,WREG
	ANDLW B'11111110'
	MOVWF 0X10
	RRNCF 0X10
	
    SHIFTQ:
	RRNCF 0X00
	BTFSC 0X12, 0
	GOTO SETQ1
	MOVFF 0X00,WREG
	ANDLW B'01111111'
	MOVWF 0X00
	GOTO BOOTH
	
    
    COMPLENT0:
	NEGF 0X00
	MOVLW 0XFF
	MOVWF 0X20
	GOTO CHECKNEGATIVE1

    COMPLENT1:
	NEGF 0X01
	MOVLW 0XFF
	CPFSEQ 0X20
	GOTO POSITIVE
	GOTO NEGATIVE
	
    POSITIVE:
	MOVLW 0X00
	MOVWF 0X20
	GOTO LOOP
	
    NEGATIVE:
	MOVLW 0XFF
	MOVWF 0X20
	GOTO LOOP
	
    SETA1:
	RRNCF 0X10
	MOVFF 0X10,WREG
	IORLW B'10000000'
	MOVWF 0X10
	GOTO SHIFTQ
	
    SETQ1:
	MOVFF 0X00,WREG
	IORLW B'10000000'
	MOVWF 0X00
	GOTO BOOTH

	
    LAST:
	MOVFF 0X00,WREG
	ANDLW 0XF0
	MOVWF 0X14
	RRNCF 0X14
	RRNCF 0X14
	RRNCF 0X14
	RRNCF 0X14
	
	MOVFF 0X10,WREG
	ANDLW 0X0F
	MOVWF 0X15
	RRNCF 0X15
	RRNCF 0X15
	RRNCF 0X15
	RRNCF 0X15
	
	MOVFF 0X00,WREG
	IORWF 0X10,W
	MOVWF 0X02
	
	MOVLW 0XFF
	CPFSEQ 0X20
	GOTO POSITIVERESULT
	GOTO NEGATIVERESULT
	
	POSITIVERESULT:
	    GOTO ALLEND
	NEGATIVERESULT:
	    NEGF 0X02
	    
	ALLEND:
	    CLREF
    
end