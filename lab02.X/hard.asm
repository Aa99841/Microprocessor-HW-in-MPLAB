List p=18f4520
    #include<p18f4520.inc>
    CONFIG OSC = INTIO67
    CONFIG WDT = OFF
    org 0x00
    
    MOVLB 0x3  ;BSR = 3
    
    ;INPUT
    MOVLW 0xC4
    MOVWF 0x20,1
    MOVLW 0xBB
    MOVWF 0x21,1
    MOVLW 0x00
    MOVWF 0x22,1
    MOVLW 0x4C
    MOVWF 0x23,1
    MOVLW 0x8B
    MOVWF 0x24,1
    MOVLW 0xBB
    MOVWF 0x25,1
    MOVLW 0x00
    MOVWF 0x26,1
    MOVLW 0x3E
    MOVWF 0x27,1
    
    MOVLW 0xFF ; COUNT I
    MOVWF 0x00
    MOVLW 0xFF ; COUNT J
    MOVWF 0x01
    
    MOVLW 0X00
    MOVWF 0X02;PAIR COUNT
    
    MOVLW 0x08
    MOVWF 0x10  ;TOTAL COUNT
    
    LFSR 0, 0x300    ; FSR0 point to 0x300(S)
    LFSR 1, 0x31F    ; FSR1 point to 0x310(I)
    LFSR 2, 0x31F    ; FSR2 point to 0x320(J)
    
    LOOP1:
	INCF 0X00
	MOVF 0X10, W
	CPFSLT 0X00
	GOTO CHECK  ;I = 8 END THE LOOP
	MOVF PREINC1, W
	MOVFF FSR1L, FSR2L
	MOVFF FSR1H, FSR2H
	MOVF POSTINC2, W ;FSR2 = FSR1 -> NEXT 
	MOVF 0X00, W ;MOVLW 0xFF ; COUNT J
	MOVWF 0x01
	GOTO LOOP2
    
    LOOP2:
	INCF 0X01
	MOVF 0X10, W
	CPFSLT 0X01 ;J = 8 BACK TO LOOP1
	    GOTO LOOP1
	MOVF INDF1, W
	MOVWF 0x11
	MOVF POSTINC2, W
	MOVWF 0x12
	RRNCF 0X12
	RRNCF 0X12
	RRNCF 0X12
	RRNCF 0X12
	MOVF 0X12,W
	CPFSEQ 0X11 ;CHECK MINOR OR NOT
	    GOTO LOOP2
	GOTO FINDPAIR
	
    FINDPAIR:
	INCF 0X02
	MOVF POSTDEC2, W
	MOVF INDF1, W  ;WREG = FSR1
	SUBWF INDF2,W  ;WREG = WREG - FSR2
	BC BIGGER2
	BNC BIGGER1
	
    BIGGER2: ;FSR2 IS BIGGER
	MOVF INDF1, W
	MOVWF POSTINC0
	MOVF INDF2, W
	MOVWF POSTINC0
	GOTO LOOP1
	
    BIGGER1: ;FSR1 IS BIGGER
	MOVF INDF2, W
	MOVWF POSTINC0
	MOVF INDF1, W
	MOVWF POSTINC0
	GOTO LOOP1
	
    CHECK:
	MOVLW 0x04 
	CPFSLT 0X02 ;PAIR COUNT = 4 ?
	GOTO SORT
	GOTO ALLFF

    SORT:
	LFSR 0, 0x2FE    ; FSR0 point to 0x2FE()
	LFSR 1, 0x2FF    ; FSR1 point to 0x2FF(I)
	LFSR 2, 0x2FF    ; FSR2 point to 0x2FF(J)
	MOVF 0X02,W
	MOVWF 0X03
	MOVWF 0X04
	GOTO SORTLOOP1
	
    SORTLOOP1:
	DECF 0X02
	BZ FILLIN
	MOVF 0X04,W
	MOVWF 0X03
	MOVF PREINC0, W
	MOVF PREINC0, W
	MOVFF FSR0L, FSR2L
	MOVFF FSR0H, FSR2H
	MOVFF FSR0L, FSR1L
	MOVFF FSR0H, FSR1H
	MOVF POSTINC2, W
	MOVF POSTINC2, W
	GOTO SORTLOOP2
	
    SORTLOOP2:
	DECF 0X03
	BZ SORTLOOP1
	MOVF INDF0, W
	MOVWF 0x11
	MOVF INDF2, W
	MOVWF 0x12
	MOVF INDF0, W  ;WREG = FSR0
	CPFSGT 0X12
	    GOTO SORTBIGGER1
	GOTO SORTLOOP2
    
    SORTBIGGER1:
	MOVFF FSR0L, FSR1L
	MOVFF FSR0H, FSR1H
	MOVF INDF1, W  ;WREG = FSR1
	MOVWF 0x20
	MOVF INDF2, W  ;WREG = FSR2
	MOVWF INDF1
	MOVF 0x20, W
	MOVWF INDF2
	MOVF PREINC1, W  ;WREG = FSR1
	MOVWF 0x20
	MOVF PREINC2, W  ;WREG = FSR2
	MOVWF INDF1
	MOVF 0x20, W
	MOVWF INDF2
	MOVF POSTINC1, W
	MOVF POSTINC2, W
	GOTO SORTLOOP2
    
    ALLFF:
	MOVLW 0xFF
	MOVWF 0x20,1
	MOVWF 0x21,1
	MOVWF 0x22,1
	MOVWF 0x23,1
	MOVWF 0x24,1
	MOVWF 0x25,1
	MOVWF 0x26,1
	MOVWF 0x27,1
	GOTO LAST
    
    FILLIN:
	LFSR 0, 0x320    ; FSR0 point to 0x320(START)
	LFSR 1, 0x327    ; FSR1 point to 0x327(END)
	LFSR 2, 0x300    ; FSR1 point to 0x300(FILL)
	INCF 0X04
	
    FILLLOOP:
	DECF 0X04
	BZ LAST
	MOVF POSTINC2, W  ;WREG = FSR2
	MOVWF POSTINC0
	MOVF POSTINC2,W
	MOVWF POSTDEC1
	GOTO FILLLOOP
    
    LAST:
	CLRF 0X00
    END


