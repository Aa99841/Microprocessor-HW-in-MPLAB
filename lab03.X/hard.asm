List p=18f4520
    #include<p18f4520.inc>
    CONFIG OSC = INTIO67
    CONFIG WDT = OFF
    org 0x00

    ; mul [0x00] and [0x001] using shift and add (range -8~7) => don't need to deal overflow
    MOVLW 0XFC ;Q
    MOVWF 0X00
    MOVLW 0XFE
    MOVWF 0X01 ;M
    
    CHECKNEGATIVE0:
	MOVLW 0X08
	CPFSLT 0X00
	    GOTO COMPLENT0 
    
    CHECKNEGATIVE1:
	MOVLW 0X08
	CPFSLT 0X01
	    GOTO COMPLENT1
	GOTO SHIFTADD1
	
    COMPLENT0:
	NEGF 0X00
	MOVLW 0XFF
	MOVWF 0X20
	GOTO CHECKNEGATIVE1

    COMPLENT1:
	NEGF 0X01
	
	; if it come here it will be at least one negative
	MOVLW 0XFF
	CPFSEQ 0X20
	    GOTO NEGATIVE ; if (come here && 0x20 != 0xff ) only one negative
	GOTO POSITIVE ; if (come here && 0x20 == 0xff ) ????
	
    POSITIVE:
	MOVLW 0X00
	MOVWF 0X20
	GOTO SHIFTADD1
	
    NEGATIVE:
	MOVLW 0XFF
	MOVWF 0X20
	GOTO SHIFTADD1
	
    SHIFTADD1:
	BTFSC 0X01, 0
	GOTO ADD1
	
    SHIFTADD2:	
	RLNCF 0X00
	BTFSC 0X01, 1
	GOTO ADD2
	
    SHIFTADD3:
	RLNCF 0X00
	BTFSC 0X01, 2
	GOTO ADD3
	
    SHIFTADD4:
	RLNCF 0X00
	BTFSC 0X01, 3
	GOTO ADD4
	GOTO LAST
	
    ADD1:
	MOVFF 0X00,WREG
	ADDWF 0X02
	GOTO SHIFTADD2
    ADD2:
	MOVFF 0X00,WREG
	ADDWF 0X02
	GOTO SHIFTADD3
    ADD3:
	MOVFF 0X00,WREG
	ADDWF 0X02
	GOTO SHIFTADD4
    ADD4:
	MOVFF 0X00,WREG
	ADDWF 0X02
	GOTO LAST
	
    LAST:
        MOVLW 0XFF
	CPFSEQ 0X20 
	GOTO POSITIVERESULT
	GOTO NEGATIVERESULT
	
    POSITIVERESULT:
	GOTO ALLEND
	
    NEGATIVERESULT:
        NEGF 0X02
	   
    ALLEND:
	CLRF WREG

	    
end
