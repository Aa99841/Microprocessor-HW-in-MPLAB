List p=18f4520
    #include<p18f4520.inc>
    CONFIG OSC = INTIO67
    CONFIG WDT = OFF
    org 0x00
   
    ;[0x000][0x001] - [0x010][0x011] = [0x020][0x021]
    MOVLW 0X9A
    MOVWF 0X00
    MOVLW 0XBC
    MOVWF 0X01
    
    MOVLW 0X99
    MOVWF 0X10
    MOVLW 0XBD
    MOVWF 0X11
    
    PART1:
	MOVFF 0X01,WREG
	CPFSGT 0X11  ; if([0x11] <= [0x01]) goto noborrow 
	    GOTO NOBORROW
	GOTO BORROW
        
    NOBORROW:
	NEGF 0X11
	MOVFF 0X11,WREG
	ADDWF 0X01,W
	MOVWF 0X21
	GOTO PART2
    
    BORROW:
	MOVLW 0XFF
	NEGF 0X11
	ADDWF 0X11,W
	ADDLW 0X01
	ADDWF 0X01,W
	MOVWF 0X21
	MOVLW 0XFF
	ADDWF 0X00
	
    PART2:
	NEGF 0X10
	MOVFF 0X10,WREG
	ADDWF 0X00,W
	MOVWF 0X20
	
END    


