	MOVWF 0X10
	
    INIT:   
	LFSR 0, 0X010; 
	LFSR 1, 0X011
	LFSR 2, 0X012
	
	MOVLW 0X01
	SUBWF 0X00
	
	MOVLW 0X00
	CPFSEQ 0X00
	    GOTO FIB
