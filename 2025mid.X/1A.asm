List p=18f4520
    #include<p18f4520.inc>
    CONFIG OSC = INTIO67
    CONFIG WDT = OFF
    org 0x00
    
    MAIN:
	MOVLW 0X63
	MOVWF 0X00
	MOVLW 0XC6
	MOVWF 0X01
	
	MOVLW 0X07
  	MOVWF 0X20

    BITTEST:
	BTFSC 0X00,6
	    GOTO BITTEST1
	GOTO BITTEST0
	
    BITTEST1:
	BTFSC 0X01,0
	    GOTO SHIFTBACK
	GOTO FALSE
	
    BITTEST0:
	BTFSC 0X01,0
	    GOTO FALSE
	GOTO SHIFTBACK
	
    SHIFTBACK:
	RRNCF 0X01
	RLNCF 0X00
	DECF 0X20
	BNZ BITTEST
	
    TRUE:
	MOVLW 0XFF
	GOTO LAST
	
    FALSE:
	MOVLW 0X00
	GOTO LAST
	
    LAST:
	MOVWF 0X10

END