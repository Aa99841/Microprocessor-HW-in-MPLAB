List p=18f4520
    #include<p18f4520.inc>
    CONFIG OSC = INTIO67
    CONFIG WDT = OFF
    org 0x00

    MAIN:
	MOVLW 0X05
	MOVWF 0X00
	MOVLW 0X05
	MOVWF 0X01
	MOVLW 0X05
	MOVWF 0X02
	MOVLW 0X05
	MOVWF 0X03
	MOVLW 0X05
	MOVWF 0X04 
	
	MOVLW 0X0A
	MOVWF 0X05
	
	MOVLW 0X05
	MOVWF 0X20
	
	LFSR 0, 0X00
	
    LOOP:
	DECF 0X20
	BZ LAST
	;FSR2 = FSR0 + 1
	MOVFF FSR0L, FSR2L
	MOVFF FSR0H, FSR2H
	MOVF POSTINC2, W ;FSR2 = FSR0 -> NEXT 
	
	MOVFF 0X20, 0X21
	GOTO LOOP2
	
    LOOP2:
	MOVF INDF0, W
	ADDWF POSTINC2,W
	CPFSEQ 0X05
	    GOTO FOR_J
	INCF 0X10
	
    FOR_J:
	DECF 0X21
	BZ FOR_I
	GOTO LOOP2
	
    FOR_I:
	MOVF POSTINC0, W
	GOTO LOOP
	
	
    LAST:
	NOP
	
	
	

END