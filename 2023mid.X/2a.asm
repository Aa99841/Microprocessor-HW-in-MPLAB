List p=18f4520
    #include<p18f4520.inc>
    CONFIG OSC = INTIO67
    CONFIG WDT = OFF
    org 0x00

    MIAN:
	MOVLW 0X09
	MOVWF 0X00
	  
    INIT1:
	MOVLW 0X01
	CPFSLT 0X00
	    MOVWF 0X10
	GOTO INIT2
    INIT2:
	MOVLW 0X02
	CPFSLT 0X00
	    MOVWF 0X11
	GOTO INIT3
    INIT3:
	MOVLW 0X04
	CPFSLT 0X00
	    MOVWF 0X12
	GOTO INIT
	
    INIT:   
	LFSR 0, 0X010 
	LFSR 2, 0X012
	
	MOVLW 0X02
	SUBWF 0X00
	
	MOVLW 0X02
	CPFSLT 0X00
	    GOTO FIB
	GOTO GRAY
    
    FIB:
	DECF 0X00
	BZ GRAY
	
	; (SFR0++ + SFR2) + SFR0++ = ++SFR2
	MOVFF POSTINC0, WREG
	ADDWF INDF2,W
	ADDWF POSTINC0,W
	MOVWF PREINC2
	
	;SFR0--
	MOVF POSTDEC0,W	
	
	GOTO FIB
	
    GRAY:
	NOP

    
END