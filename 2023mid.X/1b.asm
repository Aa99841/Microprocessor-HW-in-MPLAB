List p=18f4520
    #include<p18f4520.inc>
    CONFIG OSC = INTIO67
    CONFIG WDT = OFF
    org 0x00
    
    MIAN:
	MOVLW 0X02
	MOVWF 0X00
	
	MOVLW 0X03
	CPFSLT 0X00
	    GOTO INIT
	    
	MOVLW 0X01
	CPFSEQ 0X00
	    MOVWF 0X11
	MOVWF 0X10
	
    INIT:   
	LFSR 0, 0X010; 
	LFSR 1, 0X011
	LFSR 2, 0X012
	
	MOVLW 0X01
	SUBWF 0X00
	
	MOVLW 0X00
	CPFSEQ 0X00
	    GOTO FIB
	GOTO GRAY
    
    FIB:
	DECF 0X00
	BZ GRAY
	
	MOVFF POSTINC0, WREG
	ADDWF POSTINC1,W
	MOVWF POSTINC2
	
	GOTO FIB
	
    GRAY:
	NOP

end


