List p=18f4520
    #include<p18f4520.inc>
    CONFIG OSC = INTIO67
    CONFIG WDT = OFF
    org 0x00
    
    MIAN:
	MOVLW 0X0D
	MOVWF 0X00
	MOVWF 0X01
	    
	MOVLW 0X02
	CPFSLT 0X00
	    GOTO INIT1
	MOVLW 0X01
	MOVWF 0X10
	GOTO INIT
	
    INIT1:
	MOVLW 0X01
	MOVWF 0X11
	MOVLW 0X01
	MOVWF 0X10
	
    INIT:   
	LFSR 0, 0X010; 
	LFSR 1, 0X011
	LFSR 2, 0X012
	
	MOVLW 0X01
	SUBWF 0X00
	
	MOVLW 0X00
	CPFSEQ 0X00
	    GOTO FIB
	GOTO GRAY
    
    FIB:
	DECF 0X00
	BZ GRAY
	
	MOVFF POSTINC0, WREG
	ADDWF POSTINC1,W
	MOVWF POSTINC2
	
	GOTO FIB
	
    GRAY:
	LFSR 2,0X020
	
	MOVLW B'00000001'
	MOVWF 0X20
	MOVWF 0X21
	
	MOVLW B'00000011'
	MOVWF 0X22
	MOVLW B'00000010'
	MOVWF 0X23
	MOVLW B'00000111'
	MOVWF 0X24
	MOVLW B'00001100'
	MOVWF 0X25
	MOVLW B'00001011'
	MOVWF 0X26
	MOVLW B'00011111'
	MOVWF 0X27
	MOVLW B'00110011'
	MOVWF 0X28
	MOVLW B'00101100'
	MOVWF 0X29
	MOVLW B'01110101'
	MOVWF 0X2A
	MOVLW B'11011000'
	MOVWF 0X2B
	MOVLW B'10011101'
	MOVWF 0X2C
	
    LOOP:
	DECF 0X01
	BZ LAST
	
	MOVF PREINC2,W
	GOTO LOOP

    LAST:
	MOVWF 0X00
end